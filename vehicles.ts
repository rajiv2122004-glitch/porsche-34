export function getModelBySlug(slug: string): VehicleModel | undefined {
  return vehicleModels.find((m) => m.slug === slug);
}

export function getModelById(id: string): VehicleModel | undefined {
  return vehicleModels.find((m) => m.id === id);
}

export function getPublishedModels(): VehicleModel[] {
  return vehicleModels.filter((m) => m.published);
}

export function getModelsByCategory(category: string): VehicleModel[] {
  if (category === 'all') return getPublishedModels();
  return vehicleModels.filter((m) => m.published && m.category === category);
}

export function getModelsByPowertrain(powertrain: string): VehicleModel[] {
  if (powertrain === 'all') return getPublishedModels();
  return vehicleModels.filter((m) => m.published && m.powertrain === powertrain);
}
